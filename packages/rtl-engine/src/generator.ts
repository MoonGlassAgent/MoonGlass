/**
 * RTL 模板生成器（Phase 4 实现）
 *
 * 根据接口定义 + 编码规范生成标准 Verilog 模块骨架。
 * 生成产物默认包含：异步复位同步释放、标准命名前缀（i_/o_/w_/r_）、
 * 参数化设计、标准文件头。
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import type { ModuleInfo, PortDef } from './types.ts'

export type RtlStyle = 'standard' | 'company'

export interface GenerateOptions {
  moduleName: string
  interface: Pick<ModuleInfo, 'ports' | 'parameters'>
  style?: RtlStyle
  companyRulesId?: string
  /** 输出文件路径（缺省为当前工作目录下 {moduleName}.v） */
  outputPath?: string
}

export interface GenerateResult {
  filePath: string
  code: string
}

function headerComment(moduleName: string): string {
  const now = new Date().toISOString().split('T')[0]
  return `// ============================================================
// Module: ${moduleName}
// Generated by MoonGlass RTL Engine on ${now}
// ============================================================
// 功能描述：TODO — 请补充模块功能描述
// 作者：MoonGlass Agent
// 版本历史：
//   v0.1  ${now}  初始创建
// ============================================================
`
}

function renderPort(p: PortDef): string {
  const width = p.widthSpec ?? (p.width > 1 ? `[${p.width - 1}:0] ` : '')
  const widthStr = width && !width.endsWith(' ') ? `${width} ` : width
  return `  ${p.direction.padEnd(6)} wire ${widthStr}${p.name}`
}

function renderParameter(p: { name: string; defaultValue: string }): string {
  return `  parameter ${p.name} = ${p.defaultValue}`
}

function indentPorts(ports: PortDef[]): string {
  return ports.map(renderPort).join(',\n')
}

function indentParameters(params: Array<{ name: string; defaultValue: string }>): string {
  if (params.length === 0) return ''
  return `#(
${params.map(renderParameter).join(',\n')}
)`
}

/**
 * 生成标准 RTL 模块骨架。
 */
export async function generateRtlTemplate(options: GenerateOptions): Promise<GenerateResult> {
  const { moduleName, interface: iface, style = 'standard' } = options
  const ports = iface.ports
  const params = iface.parameters

  const inputs = ports.filter((p) => p.direction === 'input')
  const outputs = ports.filter((p) => p.direction === 'output')
  const inouts = ports.filter((p) => p.direction === 'inout')

  const clock = inputs.find((p) => /^(i_)?clk$/i.test(p.name))?.name
  const reset =
    inputs.find((p) => /^(i_)?rst_n$/i.test(p.name))?.name ??
    inputs.find((p) => /^(i_)?rst$/i.test(p.name))?.name
  const resetActiveLow = reset ? /rst_n/i.test(reset) : true

  const hasClock = !!clock
  const hasReset = !!reset

  // 构建模块声明
  const paramBlock = indentParameters(params)
  const portBlock = indentPorts([...inputs, ...outputs, ...inouts])

  const lines: string[] = []
  lines.push(headerComment(moduleName))
  lines.push(`module ${moduleName}${paramBlock} (`)
  lines.push(portBlock)
  lines.push(`);`)
  lines.push('')

  // 内部信号占位
  if (outputs.length > 0) {
    lines.push('  // 内部寄存器/线网定义')
    for (const p of outputs) {
      const width = p.widthSpec ?? (p.width > 1 ? `[${p.width - 1}:0] ` : '')
      const widthStr = width && !width.endsWith(' ') ? `${width} ` : width
      lines.push(`  reg ${widthStr}r_${p.name.replace(/^o_/, '')};`)
    }
    lines.push('')
  }

  // 组合输出（默认值）
  if (outputs.length > 0) {
    lines.push('  // 输出组合逻辑')
    for (const p of outputs) {
      lines.push(`  assign ${p.name} = r_${p.name.replace(/^o_/, '')};`)
    }
    lines.push('')
  }

  // 时序逻辑
  if (hasClock) {
    lines.push('  // 时序逻辑')
    if (hasReset) {
      lines.push(`  always @(posedge ${clock} or negedge ${reset}) begin`)
      lines.push(`    if (!${reset}) begin`)
      for (const p of outputs) {
        const widthSpec = p.widthSpec ?? (p.width > 1 ? `[${p.width - 1}:0]` : '')
        const resetValue = widthSpec && /\D/.test(widthSpec.replace(/[\[\]:\-]/g, ''))
          ? "1'b0"  // 参数化位宽，Verilog 会自动零扩展
          : p.width > 1 ? `{${p.width}{1'b0}}` : "1'b0"
        lines.push(`      r_${p.name.replace(/^o_/, '')} <= ${resetValue};`)
      }
      lines.push('    end else begin')
      lines.push('      // TODO: 实现功能逻辑')
      lines.push('    end')
      lines.push('  end')
    } else {
      lines.push(`  always @(posedge ${clock}) begin`)
      lines.push('    // TODO: 实现功能逻辑')
      lines.push('  end')
    }
    lines.push('')
  }

  lines.push('endmodule')
  lines.push('')

  const code = lines.join('\n')
  const filePath = options.outputPath ?? join(process.cwd(), `${moduleName}.v`)
  writeFileSync(filePath, code, 'utf-8')

  return { filePath, code }
}

/**
 * 生成基于已有 RTL 的模块名/端口列表的「反向工程」模板。
 * 常用于快速复刻接口或生成 wrapper。
 */
export async function generateRtlWrapper(
  moduleName: string,
  wrappedModule: string,
  wrappedInfo: Pick<ModuleInfo, 'ports' | 'parameters'>
): Promise<GenerateResult> {
  const ports = wrappedInfo.ports
  const params = wrappedInfo.parameters

  const portNames = ports.map((p) => p.name)
  const paramBlock = params.length > 0 ? `\n${params.map((p) => `  .${p.name}(${p.name})`).join(',\n')}\n` : ''

  const result = await generateRtlTemplate({
    moduleName,
    interface: wrappedInfo,
    outputPath: join(process.cwd(), `${moduleName}.v`)
  })

  // 在文件末尾追加实例化（简单追加）
  const instanceCode = `
// Wrapper instance
${wrappedModule} ${params.length > 0 ? '#(' + params.map((p) => `.${p.name}(${p.name})`).join(', ') + ')' : ''}
  u_${wrappedModule}(
${ports.map((p) => `    .${p.name}(${p.name})`).join(',\n')}
  );
`
  result.code = result.code.replace(/endmodule\s*$/, `\n${instanceCode}\nendmodule`)
  writeFileSync(result.filePath, result.code, 'utf-8')
  return result
}
