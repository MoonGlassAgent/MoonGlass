def generate_dut_template(name: str, output_dir: Path, params: dict):
    """Generate DUT template"""
    addr_width = params.get('ADDR_WIDTH', 32)
    data_width = params.get('DATA_WIDTH', 32)
    
    dut_content = f"""//-----------------------------------------------------------------------------
// Module: {name}
// Description: DUT template for Cocotb verification
// Generated by Cocotb Verification Skill
// Date: {datetime.now().strftime('%Y-%m-%d')}
//-----------------------------------------------------------------------------

module {name} #(
    parameter ADDR_WIDTH = {addr_width},
    parameter DATA_WIDTH = {data_width}
)(
    input  wire                   clk,
    input  wire                   rst_n,
    
    // Interface signals - modify according to your design
    input  wire [ADDR_WIDTH-1:0]  addr,
    input  wire [DATA_WIDTH-1:0]  wdata,
    output reg  [DATA_WIDTH-1:0]  rdata,
    input  wire                   write,
    input  wire                   valid,
    output reg                    ready
);

    // Internal registers (example)
    reg [DATA_WIDTH-1:0] registers [0:15];
    
    // Read logic
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rdata <= 0;
            ready <= 0;
        end else begin
            if (valid) begin
                if (write) begin
                    registers[addr[3:0]] <= wdata;
                    ready <= 1;
                end else begin
                    rdata <= registers[addr[3:0]];
                    ready <= 1;
                end
            end else begin
                ready <= 0;
            end
        end
    end

endmodule
"""

    output_path = output_dir / f'{name}.v'
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(dut_content)

    print(f"  Generated: {output_path}")


