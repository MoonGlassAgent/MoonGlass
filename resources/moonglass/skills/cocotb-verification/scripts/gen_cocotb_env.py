def copy_vip(vip_type: str, output_dir: Path, name: str):
    """Copy VIP files to output directory"""
    vip_source = TEMPLATE_DIR / 'vip' / vip_type
    vip_dest = output_dir / 'vip' / vip_type
    
    if vip_source.exists():
        import shutil
        shutil.copytree(vip_source, vip_dest, dirs_exist_ok=True)
        print(f"  Copied VIP: {vip_type}")


def parse_interface_spec(spec: str) -> dict:
    """Parse interface specification string"""
    params = {}

    if not spec:
        return params

    # Format: "param1=value1,param2=value2"
    for item in spec.split(','):
        if '=' in item:
            key, value = item.split('=', 1)
            key = key.strip().upper()
            try:
                params[key] = int(value.strip())
            except ValueError:
                params[key] = value.strip()

    return params


