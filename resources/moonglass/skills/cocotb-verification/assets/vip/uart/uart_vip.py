# UART Environment
# ============================================================
class UARTEnvironment:
    """UART验证环境"""
    
    def __init__(self, dut, name: str = "uart_env", config: UARTConfig = None):
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or UARTConfig()
        
        # 组件
        self.tx = UARTTransmitter(dut, f"{name}_tx", config)
        self.rx = UARTReceiver(dut, f"{name}_rx", config)
        self.scoreboard = UARTScoreboard(f"{name}_scoreboard")
        
        # 连接
        self.rx.add_callback(self.scoreboard.check)
    
    async def run(self):
        """运行环境"""
        cocotb.start_soon(self.rx.run())
    
    async def send(self, data: bytes):
        """发送数据"""
        self.scoreboard.add_expected(data)
        await self.tx.send_bytes(data)
    
    async def send_string(self, s: str):
        """发送字符串"""
        await self.send(s.encode('ascii'))
    
    def report(self):
        """生成报告"""
        self.log.info(f"TX: {self.tx.trans_count} bytes")
        self.log.info(f"RX: {self.rx.trans_count} bytes, "
                      f"parity_err={self.rx.parity_errors}, "
                      f"frame_err={self.rx.frame_errors}")
        self.scoreboard.report()


