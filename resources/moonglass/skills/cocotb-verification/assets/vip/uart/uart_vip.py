# UART Scoreboard
# ============================================================
class UARTScoreboard:
    """UART记分板"""
    
    def __init__(self, name: str = "uart_scoreboard"):
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        
        self.expected: List[int] = []
        self.actual: List[int] = []
        
        self.matched = 0
        self.mismatched = 0
    
    def add_expected(self, data: bytes):
        """添加预期数据"""
        self.expected.extend(list(data))
    
    def check(self, trans: UARTTransaction):
        """检查事务"""
        self.actual.append(trans.data)
        
        if self.expected:
            exp = self.expected.pop(0)
            if trans.data == exp and not trans.parity_error and not trans.frame_error:
                self.matched += 1
            else:
                self.mismatched += 1
                self.log.error(
                    f"Mismatch: expected=0x{exp:02X}, "
                    f"actual=0x{trans.data:02X}, "
                    f"parity_err={trans.parity_error}, "
                    f"frame_err={trans.frame_error}"
                )
    
    def get_result(self) -> bool:
        return self.mismatched == 0 and len(self.expected) == 0
    
    def report(self):
        self.log.info(f"\n=== {self.name} Report ===")
        self.log.info(f"Matched: {self.matched}, Mismatched: {self.mismatched}")
        self.log.info(f"Pending: {len(self.expected)}")


