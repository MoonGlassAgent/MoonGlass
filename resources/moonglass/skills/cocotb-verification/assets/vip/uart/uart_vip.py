# UART Receiver (RX)
# ============================================================
class UARTReceiver:
    """
    UART接收器
    
    将串行UART信号转换为并行数据
    """
    
    def __init__(self, dut, name: str = "uart_rx", config: UARTConfig = None):
        """
        初始化UART接收器
        
        Args:
            dut: DUT句柄
            name: 接收器名称
            config: UART配置
        """
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or UARTConfig()
        
        # 接收数据
        self.received: List[UARTTransaction] = []
        self.callbacks = []
        
        # 统计
        self.trans_count = 0
        self.parity_errors = 0
        self.frame_errors = 0
        
        self.log.info(f"{name} initialized")
    
    def add_callback(self, callback):
        """添加回调函数"""
        self.callbacks.append(callback)
    
    async def receive_byte(self) -> UARTTransaction:
        """
        接收单个字节
        
        Returns:
            UARTTransaction: 接收的事务
        """
        dut = self.dut
        bit_time = self.config.bit_time_ns
        
        # 获取RX信号
        rx_signal = getattr(dut, 'uart_rx', getattr(dut, 'rxd', None))
        if rx_signal is None:
            raise ValueError("UART RX signal not found")
        
        trans = UARTTransaction()
        
        # 等待Start bit (下降沿)
        while rx_signal.value == 1:
            await Timer(int(bit_time / 2), units='ns')
        
        # 确认Start bit (在位中间采样)
        await Timer(int(bit_time), units='ns')
        if rx_signal.value != 0:
            trans.frame_error = True
            self.frame_errors += 1
            self.log.warning("Frame error: Start bit not detected")
            return trans
        
        # 采样数据位
        data = 0
        parity = 0
        for i in range(self.config.data_bits):
            await Timer(int(bit_time), units='ns')
            bit = int(rx_signal.value)
            data |= (bit << i)
            parity ^= bit
        
        trans.data = data
        
        # 校验Parity bit
        if self.config.parity == 'even':
            await Timer(int(bit_time), units='ns')
            received_parity = int(rx_signal.value)
            if received_parity != parity:
                trans.parity_error = True
                self.parity_errors += 1
                self.log.warning(f"Parity error: data=0x{data:02X}")
        elif self.config.parity == 'odd':
            await Timer(int(bit_time), units='ns')
            received_parity = int(rx_signal.value)
            if received_parity != (1 - parity):
                trans.parity_error = True
                self.parity_errors += 1
        
        # 检查Stop bit
        await Timer(int(bit_time), units='ns')
        if rx_signal.value != 1:
            trans.frame_error = True
            self.frame_errors += 1
            self.log.warning("Frame error: Stop bit not detected")
        
        self.trans_count += 1
        self.received.append(trans)
        
        # 调用回调
        for cb in self.callbacks:
            cb(trans)
        
        self.log.debug(f"Received: {trans}")
        return trans
    
    async def run(self):
        """主运行循环"""
        while True:
            try:
                await self.receive_byte()
            except Exception as e:
                self.log.error(f"Receive error: {e}")
                await Timer(int(self.config.bit_time_ns), units='ns')
    
    def get_data(self) -> bytes:
        """获取接收的字节数据"""
        return bytes(trans.data for trans in self.received)


