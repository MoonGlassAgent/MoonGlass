# UART Transmitter (TX)
# ============================================================
class UARTTransmitter:
    """
    UART发送器
    
    将并行数据转换为串行UART信号
    """
    
    def __init__(self, dut, name: str = "uart_tx", config: UARTConfig = None):
        """
        初始化UART发送器
        
        Args:
            dut: DUT句柄
            name: 发送器名称
            config: UART配置
        """
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or UARTConfig()
        
        # 发送队列
        self.queue: queue.Queue = queue.Queue()
        
        # 统计
        self.trans_count = 0
        self.bytes_count = 0
        
        self.log.info(
            f"{name} initialized "
            f"(baud={self.config.baud_rate}, "
            f"bit_time={self.config.bit_time_us:.2f}us)"
        )
    
    async def send_byte(self, data: int) -> None:
        """
        发送单个字节
        
        UART帧格式:
        [Start Bit] [Data Bits] [Parity Bit] [Stop Bit(s)]
             0       D0...D7       P           1...
        """
        dut = self.dut
        bit_time = self.config.bit_time_ns
        
        # 获取TX信号 (假设信号名为uart_tx或txd)
        tx_signal = getattr(dut, 'uart_tx', getattr(dut, 'txd', None))
        if tx_signal is None:
            raise ValueError("UART TX signal not found")
        
        # Start bit (0)
        tx_signal.value = 0
        await Timer(int(bit_time), units='ns')
        
        # Data bits (LSB first)
        parity = 0
        for i in range(self.config.data_bits):
            bit = (data >> i) & 1
            tx_signal.value = bit
            parity ^= bit
            await Timer(int(bit_time), units='ns')
        
        # Parity bit
        if self.config.parity == 'even':
            tx_signal.value = parity
            await Timer(int(bit_time), units='ns')
        elif self.config.parity == 'odd':
            tx_signal.value = 1 - parity
            await Timer(int(bit_time), units='ns')
        
        # Stop bit(s) (1)
        tx_signal.value = 1
        for _ in range(self.config.stop_bits):
            await Timer(int(bit_time), units='ns')
        
        self.trans_count += 1
        self.bytes_count += 1
        self.log.debug(f"Sent: 0x{data:02X}")
    
    async def send_bytes(self, data: bytes) -> None:
        """发送多个字节"""
        for b in data:
            await self.send_byte(b)
    
    async def send_string(self, s: str) -> None:
        """发送字符串"""
        await self.send_bytes(s.encode('ascii'))
    
    async def run(self):
        """主运行循环"""
        while True:
            try:
                data = self.queue.get_nowait()
                await self.send_byte(data)
            except queue.Empty:
                await Timer(100, units='ns')


