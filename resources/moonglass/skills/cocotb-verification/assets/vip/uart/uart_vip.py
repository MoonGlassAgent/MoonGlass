# ============================================================
# UART Configuration
# ============================================================
@dataclass
class UARTConfig:
    """UART配置"""
    baud_rate: int = 115200
    data_bits: int = 8
    parity: str = 'none'      # 'none', 'even', 'odd'
    stop_bits: int = 1
    
    @property
    def bit_time_ns(self) -> float:
        """计算位时间(纳秒)"""
        return 1_000_000_000 / self.baud_rate
    
    @property
    def bit_time_us(self) -> float:
        """计算位时间(微秒)"""
        return 1_000_000 / self.baud_rate


# ============================================================
# UART Transaction
# ============================================================
@dataclass
class UARTTransaction:
    """UART事务"""
    data: int = 0
    parity_error: bool = False
    frame_error: bool = False
    
    def __str__(self):
        return f"[UART] data=0x{self.data:02X} ({chr(self.data) if 32 <= self.data < 127 else '?'})"


