# SPI Transaction
# ============================================================
@dataclass
class SPITransaction:
    """SPI事务"""
    mosi_data: int = 0       # Master Out Data
    miso_data: int = 0       # Master In Data
    cs: int = 0              # Chip Select
    bits: int = 8            # 传输位数
    
    def __str__(self):
        return f"[SPI] MOSI=0x{self.mosi_data:02X}, MISO=0x{self.miso_data:02X}, CS={self.cs}"


