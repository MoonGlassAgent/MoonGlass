# ============================================================
# SPI Configuration
# ============================================================
class SPIMode(Enum):
    """SPI模式"""
    MODE_0 = 0  # CPOL=0, CPHA=0
    MODE_1 = 1  # CPOL=0, CPHA=1
    MODE_2 = 2  # CPOL=1, CPHA=0
    MODE_3 = 3  # CPOL=1, CPHA=1


@dataclass
class SPIConfig:
    """SPI配置"""
    mode: SPIMode = SPIMode.MODE_0
    clk_freq: int = 1_000_000  # 1 MHz
    data_width: int = 8
    cs_active_low: bool = True
    lsb_first: bool = False
    
    @property
    def cpol(self) -> int:
        """时钟极性"""
        return (self.mode.value >> 1) & 1
    
    @property
    def cpha(self) -> int:
        """时钟相位"""
        return self.mode.value & 1
    
    @property
    def half_period_ns(self) -> float:
        """半周期时间(纳秒)"""
        return 1_000_000_000 / self.clk_freq / 2


