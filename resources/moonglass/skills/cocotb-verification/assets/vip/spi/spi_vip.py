class SPIEnvironment:
    """SPI验证环境"""
    
    def __init__(self, dut, name: str = "spi_env", config: SPIConfig = None):
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or SPIConfig()
        
        # 组件
        self.driver = SPIMasterDriver(dut, f"{name}_driver", config)
        self.monitor = SPISlaveMonitor(dut, f"{name}_monitor", config)
        self.scoreboard = SPIScoreboard(f"{name}_scoreboard")
        
        # 连接
        self.monitor.add_callback(self.scoreboard.check)
    
    async def run(self):
        """运行环境"""
        cocotb.start_soon(self.monitor.run())
    
    async def transfer(self, data: int) -> int:
        """执行传输"""
        return await self.driver.transfer(data)
    
    async def read_write(self, data: bytes) -> bytes:
        """读写多字节"""
        return await self.driver.read_write(data)
    
    def report(self):
        """生成报告"""
        self.log.info(f"Transfers: {self.driver.trans_count}")
        self.scoreboard.report()


