class SPISlaveMonitor:
    """
    SPI Slave监控器
    """
    
    def __init__(self, dut, name: str = "spi_monitor", config: SPIConfig = None):
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or SPIConfig()
        
        self.transactions: List[SPITransaction] = []
        self.callbacks = []
        
        self.log.info(f"{name} initialized")
    
    def add_callback(self, callback):
        """添加回调函数"""
        self.callbacks.append(callback)
    
    async def run(self):
        """监控SPI总线"""
        dut = self.dut
        
        sclk, mosi, miso, cs = self._get_signals()
        
        while True:
            # 等待片选有效
            if cs is not None:
                while (cs.value == (1 if self.config.cs_active_low else 0)):
                    await Timer(100, units='ns')
            
            # 传输数据
            mosi_data = 0
            bit_count = 0
            
            cpol = self.config.cpol
            cpha = self.config.cpha
            
            prev_sclk = cpol
            
            while cs is None or (cs.value == (0 if self.config.cs_active_low else 1)):
                await Timer(int(self.config.half_period_ns), units='ns')
                
                current_sclk = int(sclk.value)
                
                # 检测时钟边沿
                if cpha == 0:
                    # 在后沿采样
                    if prev_sclk != current_sclk and current_sclk == cpol:
                        if mosi is not None:
                            bit = int(mosi.value)
                            mosi_data = (mosi_data << 1) | bit
                            bit_count += 1
                else:
                    # 在前沿采样
                    if prev_sclk != current_sclk and current_sclk != cpol:
                        if mosi is not None:
                            bit = int(mosi.value)
                            mosi_data = (mosi_data << 1) | bit
                            bit_count += 1
                
                prev_sclk = current_sclk
                
                # 检查是否传输完成
                if bit_count >= self.config.data_width:
                    trans = SPITransaction(mosi_data=mosi_data)
                    self.transactions.append(trans)
                    
                    for cb in self.callbacks:
                        cb(trans)
                    
                    self.log.debug(f"Captured: {trans}")
                    mosi_data = 0
                    bit_count = 0
    
    def _get_signals(self):
        """获取SPI信号"""
        dut = self.dut
        sclk = getattr(dut, 'sclk', getattr(dut, 'spi_clk', None))
        mosi = getattr(dut, 'mosi', getattr(dut, 'spi_mosi', None))
        miso = getattr(dut, 'miso', getattr(dut, 'spi_miso', None))
        cs = getattr(dut, 'cs_n', getattr(dut, 'spi_cs_n', 
                getattr(dut, 'cs', getattr(dut, 'spi_cs', None))))
        return sclk, mosi, miso, cs


