class SPIScoreboard:
    """SPI记分板"""
    
    def __init__(self, name: str = "spi_scoreboard"):
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        
        self.expected: List[int] = []
        self.actual: List[int] = []
        
        self.matched = 0
        self.mismatched = 0
    
    def add_expected(self, data: int):
        """添加预期数据"""
        self.expected.append(data)
    
    def check(self, trans: SPITransaction):
        """检查事务"""
        self.actual.append(trans.mosi_data)
        
        if self.expected:
            exp = self.expected.pop(0)
            if trans.mosi_data == exp:
                self.matched += 1
            else:
                self.mismatched += 1
                self.log.error(
                    f"Mismatch: expected=0x{exp:02X}, actual=0x{trans.mosi_data:02X}"
                )
    
    def get_result(self) -> bool:
        return self.mismatched == 0 and len(self.expected) == 0
    
    def report(self):
        self.log.info(f"\n=== {self.name} Report ===")
        self.log.info(f"Matched: {self.matched}, Mismatched: {self.mismatched}")


