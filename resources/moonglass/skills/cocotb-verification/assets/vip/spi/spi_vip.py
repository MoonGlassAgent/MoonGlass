class SPIMasterDriver:
    """
    SPI Master驱动器
    """
    
    def __init__(self, dut, name: str = "spi_master", config: SPIConfig = None):
        """
        初始化SPI Master驱动器
        
        Args:
            dut: DUT句柄
            name: 驱动器名称
            config: SPI配置
        """
        self.dut = dut
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        self.config = config or SPIConfig()
        
        # 事务队列
        self.queue: List[SPITransaction] = []
        
        # 统计
        self.trans_count = 0
        
        self.log.info(
            f"{name} initialized "
            f"(mode={self.config.mode.name}, "
            f"freq={self.config.clk_freq/1e6:.1f}MHz)"
        )
    
    def _get_signals(self):
        """获取SPI信号"""
        dut = self.dut
        
        # 支持多种命名约定
        sclk = getattr(dut, 'sclk', getattr(dut, 'spi_clk', None))
        mosi = getattr(dut, 'mosi', getattr(dut, 'spi_mosi', None))
        miso = getattr(dut, 'miso', getattr(dut, 'spi_miso', None))
        cs = getattr(dut, 'cs_n', getattr(dut, 'spi_cs_n', 
                getattr(dut, 'cs', getattr(dut, 'spi_cs', None))))
        
        return sclk, mosi, miso, cs
    
    async def _half_clock(self):
        """等待半个时钟周期"""
        await Timer(int(self.config.half_period_ns), units='ns')
    
    async def transfer(self, mosi_data: int, bits: int = None) -> int:
        """
        执行SPI传输
        
        Args:
            mosi_data: 要发送的数据
            bits: 传输位数
        
        Returns:
            int: 接收的数据
        """
        if bits is None:
            bits = self.config.data_width
        
        sclk, mosi, miso, cs = self._get_signals()
        cpol = self.config.cpol
        cpha = self.config.cpha
        lsb_first = self.config.lsb_first
        
        miso_data = 0
        
        # 根据CPOL设置初始时钟状态
        sclk.value = cpol
        
        # 传输每一位
        for i in range(bits):
            bit_idx = i if lsb_first else (bits - 1 - i)
            
            # CPHA=0: 数据在时钟前沿变化，后沿采样
            # CPHA=1: 数据在时钟后沿变化，前沿采样
            
            if cpha == 0:
                # 前沿: 输出数据
                mosi.value = (mosi_data >> bit_idx) & 1
                await self._half_clock()
                
                # 切换时钟
                sclk.value = 1 - cpol
                await self._half_clock()
                
                # 后沿: 采样数据
                if miso is not None:
                    miso_data |= (int(miso.value) << bit_idx)
                
                # 恢复时钟
                sclk.value = cpol
            else:
                # 前沿: 切换时钟
                sclk.value = 1 - cpol
                await self._half_clock()
                
                # 输出数据
                mosi.value = (mosi_data >> bit_idx) & 1
                await self._half_clock()
                
                # 后沿: 采样数据并恢复时钟
                if miso is not None:
                    miso_data |= (int(miso.value) << bit_idx)
                sclk.value = cpol
        
        self.trans_count += 1
        self.log.debug(f"Transfer: MOSI=0x{mosi_data:02X}, MISO=0x{miso_data:02X}")
        
        return miso_data
    
    async def transfer_transaction(self, trans: SPITransaction) -> SPITransaction:
        """
        执行SPI事务
        
        Args:
            trans: SPI事务
        
        Returns:
            SPITransaction: 完成的事务(包含MISO数据)
        """
        sclk, mosi, miso, cs = self._get_signals()
        
        # 片选有效
        if cs is not None:
            cs.value = 0 if self.config.cs_active_low else 1
        
        # 执行传输
        trans.miso_data = await self.transfer(trans.mosi_data, trans.bits)
        
        # 片选无效
        if cs is not None:
            cs.value = 1 if self.config.cs_active_low else 0
        
        return trans
    
    async def read_write(self, data: bytes) -> bytes:
        """
        读写多字节
        
        Args:
            data: 要发送的字节
        
        Returns:
            bytes: 接收的字节
        """
        result = bytearray()
        
        sclk, mosi, miso, cs = self._get_signals()
        
        # 片选有效
        if cs is not None:
            cs.value = 0 if self.config.cs_active_low else 1
        
        for b in data:
            miso_byte = await self.transfer(b)
            result.append(miso_byte)
        
        # 片选无效
        if cs is not None:
            cs.value = 1 if self.config.cs_active_low else 0
        
        return bytes(result)
    
    async def run(self):
        """主运行循环"""
        while True:
            if self.queue:
                trans = self.queue.pop(0)
                await self.transfer_transaction(trans)
            else:
                await Timer(100, units='ns')


