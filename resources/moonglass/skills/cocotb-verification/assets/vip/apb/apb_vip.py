class APBEnvironment:
    """APB验证环境"""
    
    def __init__(self, dut, name: str = "apb_env", apb4: bool = False):
        self.dut = dut
        self.name = name
        self.log = logging.getLogger(f"cocotb.{name}")
        
        # 组件
        self.driver = APBMasterDriver(dut, f"{name}_driver", apb4)
        self.monitor = APBSlaveMonitor(dut, f"{name}_monitor")
        self.scoreboard = APBScoreboard(f"{name}_scoreboard")
        
        # 连接
        self.monitor.add_callback(self.scoreboard.check)
    
    async def reset(self):
        """复位"""
        dut = self.dut
        dut.preset_n.value = 0
        for _ in range(10):
            await RisingEdge(dut.pclk)
        dut.preset_n.value = 1
        for _ in range(5):
            await RisingEdge(dut.pclk)
    
    async def run(self):
        """运行环境"""
        cocotb.start_soon(self.monitor.run())
    
    def report(self):
        """生成报告"""
        self.driver.log.info(f"Driver transactions: {self.driver.trans_count}")
        self.scoreboard.report()


