# ============================================================
class APBScoreboard:
    """APB记分板"""
    
    def __init__(self, name: str = "apb_scoreboard"):
        self.name = name
        self.log = logging.getLogger(f"cocotb.{name}")
        
        # 寄存器模型 (简化版)
        self.registers = {}
        
        # 统计
        self.total = 0
        self.matched = 0
        self.errors = 0
    
    def write_expected(self, addr: int, data: int):
        """记录预期写入"""
        self.registers[addr] = data
    
    def check(self, trans: APBTransaction):
        """检查事务"""
        self.total += 1
        
        if trans.write:
            # 写操作: 记录预期值
            self.registers[trans.addr] = trans.data
            self.matched += 1
        else:
            # 读操作: 检查是否匹配
            expected = self.registers.get(trans.addr, 0)
            if trans.rdata == expected:
                self.matched += 1
            else:
                self.errors += 1
                self.log.error(
                    f"Read mismatch at 0x{trans.addr:04X}: "
                    f"expected=0x{expected:08X}, actual=0x{trans.rdata:08X}"
                )
    
    def report(self):
        """生成报告"""
        self.log.info(f"\n=== {self.name} Report ===")
        self.log.info(f"Total: {self.total}, Matched: {self.matched}, Errors: {self.errors}")


