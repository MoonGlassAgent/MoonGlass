class APBMasterDriver:
    """
    APB Master驱动器
    
    支持APB3和APB4协议
    """
    
    def __init__(self, dut, name: str = "apb_master", apb4: bool = False):
        """
        初始化APB Master驱动器
        
        Args:
            dut: DUT句柄
            name: 驱动器名称
            apb4: 是否使用APB4协议
        """
        self.dut = dut
        self.name = name
        self.log = logging.getLogger(f"cocotb.{name}")
        self.apb4 = apb4
        
        # 事务队列
        self.queue = []
        
        # 统计
        self.trans_count = 0
        self.error_count = 0
        
        self.log.info(f"{name} initialized (APB{'4' if apb4 else '3'})")
    
    async def drive_transaction(self, trans: APBTransaction) -> bool:
        """
        驱动APB事务
        
        APB协议时序:
        Setup phase:   PSEL=1, PWRITE=x, PADDR=x, PWDATA=x
        Access phase:  PENABLE=1, PREADY监视
        """
        dut = self.dut
        
        # Setup phase
        dut.psel.value = 1
        dut.pwrite.value = 1 if trans.write else 0
        dut.paddr.value = trans.addr
        
        if trans.write:
            dut.pwdata.value = trans.data
            if self.apb4:
                dut.pstrb.value = trans.strb
                dut.pprot.value = trans.prot
        
        await RisingEdge(dut.pclk)
        
        # Access phase
        dut.penable.value = 1
        await RisingEdge(dut.pclk)
        
        # 等待PREADY
        cycles = 0
        while dut.pready.value == 0:
            await RisingEdge(dut.pclk)
            cycles += 1
            if cycles > 100:
                self.log.error("PREADY timeout")
                return False
        
        # 采样读数据
        if not trans.write:
            trans.rdata = int(dut.prdata.value)
        
        # 采样错误响应 (APB3/APB4)
        if hasattr(dut, 'pslverr'):
            trans.slv_error = bool(dut.pslverr.value)
        
        # Idle phase
        dut.psel.value = 0
        dut.penable.value = 0
        
        self.trans_count += 1
        self.log.debug(f"Drove: {trans}")
        
        return not trans.slv_error
    
    async def write(self, addr: int, data: int, strb: int = 0xF) -> bool:
        """执行写操作"""
        trans = APBTransaction(addr=addr, data=data, write=True, strb=strb)
        return await self.drive_transaction(trans)
    
    async def read(self, addr: int) -> tuple:
        """
        执行读操作
        
        Returns:
            tuple: (success, data)
        """
        trans = APBTransaction(addr=addr, write=False)
        success = await self.drive_transaction(trans)
        return success, trans.rdata
    
    async def run(self):
        """主运行循环"""
        while True:
            if self.queue:
                trans = self.queue.pop(0)
                success = await self.drive_transaction(trans)
                if not success:
                    self.error_count += 1
            await RisingEdge(self.dut.pclk)


