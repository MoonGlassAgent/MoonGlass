# APB Transaction
# ============================================================
@dataclass
class APBTransaction:
    """APB事务"""
    addr: int = 0
    data: int = 0
    write: bool = False      # True: write, False: read
    strb: int = 0xF          # Write strobe (APB4)
    prot: int = 0            # Protection type (APB4)
    
    # 响应字段
    slv_error: bool = False  # PSLVERR
    rdata: int = 0           # Read data
    
    # 元数据
    id: int = 0
    delay: int = 0
    
    def __str__(self):
        op = "WR" if self.write else "RD"
        err = " [ERR]" if self.slv_error else ""
        return f"[APB {op}] addr=0x{self.addr:04X}, data=0x{self.data:08X}{err}"


