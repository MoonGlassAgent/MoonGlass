class APBSlaveMonitor:
    """
    APB Slave监控器
    
    监控APB总线事务
    """
    
    def __init__(self, dut, name: str = "apb_monitor"):
        self.dut = dut
        self.name = name
        self.log = logging.getLogger(f"cocotb.{name}")
        
        self.transactions: List[APBTransaction] = []
        self.callbacks = []
        
        self.log.info(f"{name} initialized")
    
    def add_callback(self, callback):
        """添加回调函数"""
        self.callbacks.append(callback)
    
    async def run(self):
        """监控APB总线"""
        dut = self.dut
        
        while True:
            await RisingEdge(dut.pclk)
            
            # 检测Access phase (PSEL=1, PENABLE=1)
            if dut.psel.value and dut.penable.value:
                # 等待PREADY
                if dut.pready.value:
                    # 采样事务
                    trans = APBTransaction(
                        addr=int(dut.paddr.value),
                        write=bool(dut.pwrite.value),
                        data=int(dut.pwdata.value) if dut.pwrite.value else int(dut.prdata.value)
                    )
                    
                    if hasattr(dut, 'pstrb'):
                        trans.strb = int(dut.pstrb.value)
                    
                    if hasattr(dut, 'pslverr'):
                        trans.slv_error = bool(dut.pslverr.value)
                    
                    self.transactions.append(trans)
                    
                    for cb in self.callbacks:
                        cb(trans)
                    
                    self.log.debug(f"Captured: {trans}")


