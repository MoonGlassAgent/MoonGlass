# Scoreboard 集成示例
# ============================================================
class GoldenModelScoreboard:
    """
    集成 Golden Model 的 Scoreboard
    """
    
    def __init__(self, golden_model: GoldenModelBase, name: str = "scoreboard"):
        self.golden_model = golden_model
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        
        # 统计
        self.matched = 0
        self.mismatched = 0
        self.errors: List[Dict] = []
    
    def compare(self, expected: Any, actual: Any) -> bool:
        """
        比较预期值和实际值
        
        Returns:
            bool: 是否匹配
        """
        # 简单比较
        if expected == actual:
            return True
        
        # 字典比较
        if isinstance(expected, dict) and isinstance(actual, dict):
            return self._compare_dict(expected, actual)
        
        # 对象比较
        if hasattr(expected, '__dict__') and hasattr(actual, '__dict__'):
            return self._compare_objects(expected, actual)
        
        return False
    
    def _compare_dict(self, expected: Dict, actual: Dict) -> bool:
        """比较两个字典"""
        for key in expected:
            if key not in actual:
                return False
            if expected[key] != actual[key]:
                return False
        return True
    
    def _compare_objects(self, expected: Any, actual: Any) -> bool:
        """比较两个对象"""
        for attr in vars(expected):
            if not hasattr(actual, attr):
                return False
            if getattr(expected, attr) != getattr(actual, attr):
                return False
        return True
    
    def check(self, transaction: Any, actual_output: Any) -> bool:
        """
        检查事务
        
        Args:
            transaction: 输入事务
            actual_output: DUT实际输出
        
        Returns:
            bool: 是否匹配
        """
        # 获取预期输出
        expected = self.golden_model.predict(transaction)
        
        # 比较
        if self.compare(expected, actual_output):
            self.matched += 1
            self.log.debug(f"Match: expected={expected}, actual={actual_output}")
            return True
        else:
            self.mismatched += 1
            error = {
                'transaction': transaction,
                'expected': expected,
                'actual': actual_output,
                'count': self.golden_model.transaction_count
            }
            self.errors.append(error)
            self.log.error(f"Mismatch: expected={expected}, actual={actual_output}")
            return False
    
    def get_pass_rate(self) -> float:
        """获取通过率"""
        total = self.matched + self.mismatched
        if total == 0:
            return 1.0
        return self.matched / total
    
    def report(self) -> None:
        """生成报告"""
        self.log.info(f"\n=== {self.name} Report ===")
        self.log.info(f"Matched: {self.matched}")
        self.log.info(f"Mismatched: {self.mismatched}")
        self.log.info(f"Pass rate: {self.get_pass_rate()*100:.2f}%")
        
        if self.errors:
            self.log.info(f"\nFirst 5 errors:")
            for i, err in enumerate(self.errors[:5]):
                self.log.info(f"  [{i+1}] Expected: {err['expected']}")
                self.log.info(f"      Actual: {err['actual']}")


