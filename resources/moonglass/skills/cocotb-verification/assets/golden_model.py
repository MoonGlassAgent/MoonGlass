class GoldenModelBase(ABC):
    """
    Golden Model 抽象基类
    
    所有参考模型应继承此类并实现:
    - reset(): 复位模型状态
    - process(): 处理输入并返回预期输出
    """
    
    def __init__(self, name: str = "golden_model"):
        self.name = name
        self.log = SimLog(f"cocotb.{name}")
        
        # 统计信息
        self.transaction_count = 0
        self.error_count = 0
        
        # 历史记录（用于调试）
        self.history: List[Dict] = []
        self.max_history = 1000
        
        self.log.info(f"{name} initialized")
    
    @abstractmethod
    def reset(self) -> None:
        """
        复位模型状态
        
        将所有内部状态恢复到初始值
        """
        raise NotImplementedError("Subclass must implement reset()")
    
    @abstractmethod
    def process(self, transaction: Any) -> Any:
        """
        处理输入事务，返回预期输出
        
        Args:
            transaction: 输入事务对象
        
        Returns:
            预期的输出事务或值
        """
        raise NotImplementedError("Subclass must implement process()")
    
    def predict(self, transaction: Any) -> Any:
        """
        预测输出（带统计和历史记录）
        
        Args:
            transaction: 输入事务
        
        Returns:
            预期输出
        """
        self.transaction_count += 1
        
        # 计算预期输出
        expected = self.process(transaction)
        
        # 记录历史
        if len(self.history) < self.max_history:
            self.history.append({
                'input': self._serialize(transaction),
                'output': self._serialize(expected),
                'count': self.transaction_count
            })
        
        return expected
    
    def _serialize(self, obj: Any) -> Any:
        """序列化对象用于记录"""
        if hasattr(obj, 'to_dict'):
            return obj.to_dict()
        elif hasattr(obj, '__dict__'):
            return str(obj)
        return obj
    
    def get_stats(self) -> Dict:
        """获取统计信息"""
        return {
            'name': self.name,
            'transactions': self.transaction_count,
            'errors': self.error_count
        }
    
    def clear_history(self) -> None:
        """清空历史记录"""
        self.history.clear()


