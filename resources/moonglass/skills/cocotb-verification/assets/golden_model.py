# 示例：FIFO Golden Model
# ============================================================
class FIFOGoldenModel(SequentialGoldenModel):
    """
    FIFO参考模型
    
    模拟FIFO的读写行为
    """
    
    def __init__(self, depth: int = 16, data_width: int = 32):
        super().__init__("fifo_model")
        
        self.depth = depth
        self.data_width = data_width
        
        # 内部存储
        self.memory: List[int] = []
    
    def reset(self) -> None:
        """复位FIFO"""
        super().reset()
        self.memory.clear()
    
    def write(self, data: int) -> bool:
        """
        写入数据
        
        Returns:
            bool: 是否成功（未满）
        """
        if len(self.memory) >= self.depth:
            return False  # FIFO已满
        
        self.memory.append(data)
        return True
    
    def read(self) -> Optional[int]:
        """
        读取数据
        
        Returns:
            数据值，如果FIFO为空则返回None
        """
        if not self.memory:
            return None
        
        return self.memory.pop(0)
    
    def is_empty(self) -> bool:
        """是否为空"""
        return len(self.memory) == 0
    
    def is_full(self) -> bool:
        """是否已满"""
        return len(self.memory) >= self.depth
    
    def count(self) -> int:
        """当前数据量"""
        return len(self.memory)
    
    def process(self, transaction: Any) -> Dict:
        """处理读写事务"""
        # 根据事务类型处理
        if hasattr(transaction, 'write_en') and transaction.write_en:
            success = self.write(transaction.data)
            return {'success': success, 'operation': 'write'}
        
        elif hasattr(transaction, 'read_en') and transaction.read_en:
            data = self.read()
            return {'data': data, 'operation': 'read', 'valid': data is not None}
        
        return {'operation': 'idle'}


