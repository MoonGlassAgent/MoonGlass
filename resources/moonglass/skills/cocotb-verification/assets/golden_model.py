class AdderGoldenModel(CombinationalGoldenModel):
    """
    加法器参考模型
    
    功能：计算 a + b + cin，输出 sum 和 cout
    """
    
    def __init__(self, data_width: int = 8):
        super().__init__("adder_model")
        self.data_width = data_width
        self.max_value = (1 << data_width) - 1
    
    def process(self, transaction: AdderTransaction) -> AdderResult:
        """计算加法结果"""
        # 计算完整结果
        total = transaction.a + transaction.b + transaction.cin
        
        # 提取 sum 和 cout
        result_sum = total & self.max_value
        result_cout = 1 if total > self.max_value else 0
        
        return AdderResult(sum=result_sum, cout=result_cout)


