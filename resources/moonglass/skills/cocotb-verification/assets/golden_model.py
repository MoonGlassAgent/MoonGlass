class RegisterFileGoldenModel(SequentialGoldenModel):
    """
    寄存器文件参考模型
    """
    
    def __init__(self, num_regs: int = 16, data_width: int = 32):
        super().__init__("regfile_model")
        
        self.num_regs = num_regs
        self.data_width = data_width
        
        # 寄存器存储
        self.registers: Dict[int, int] = {}
    
    def reset(self) -> None:
        """复位所有寄存器"""
        super().reset()
        self.registers.clear()
    
    def write(self, addr: int, data: int) -> bool:
        """写寄存器"""
        if addr >= self.num_regs:
            return False  # 地址越界
        
        self.registers[addr] = data
        return True
    
    def read(self, addr: int) -> Optional[int]:
        """读寄存器"""
        if addr >= self.num_regs:
            return None  # 地址越界
        
        return self.registers.get(addr, 0)  # 未初始化返回0
    
    def process(self, transaction: Any) -> Dict:
        """处理读写事务"""
        result = {'addr': getattr(transaction, 'addr', 0)}
        
        if hasattr(transaction, 'write') and transaction.write:
            success = self.write(transaction.addr, transaction.data)
            result['success'] = success
            result['operation'] = 'write'
        else:
            data = self.read(transaction.addr)
            result['data'] = data
            result['operation'] = 'read'
            result['valid'] = data is not None
        
        return result


