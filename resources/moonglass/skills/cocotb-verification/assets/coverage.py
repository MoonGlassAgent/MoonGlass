    def get_coverage(self, field_name: str = None) -> float:
        """
        获取覆盖率
        
        Args:
            field_name: 字段名，None表示总体覆盖率
        
        Returns:
            float: 覆盖率百分比
        """
        if field_name:
            return self.coverage_data.get(field_name, {}).get('coverage', 0.0)
        
        # 计算总体覆盖率
        if not self.coverage_data:
            return 0.0
        
        total_coverage = sum(
            data['coverage'] for data in self.coverage_data.values()
        )
        return total_coverage / len(self.coverage_data)
    
    def get_bin_count(self, field_name: str, bin_name: str) -> int:
        """获取特定仓的计数"""
        if field_name not in self.bins:
            return 0
        
        for bin_obj in self.bins[field_name]:
            if bin_obj.name == bin_name:
                return bin_obj.count
        
        return 0
    
    def get_uncovered_bins(self, field_name: str) -> List[str]:
        """获取未覆盖的仓"""
        if field_name not in self.bins:
            return []
        
        return [
            bin_obj.name for bin_obj in self.bins[field_name]
            if bin_obj.count == 0
        ]
    
    # ============================================================
    # 报告生成
