class AdvancedCoverageCollector:
    """
    高级覆盖率收集器 (需要 cocotb-coverage)
    
    使用 cocotb-coverage 库提供更强大的覆盖率功能
    """
    
    def __init__(self, name: str = "advanced_coverage"):
        self.name = name
        self.log = logging.getLogger(f"cocotb.{name}")
        
        if not HAS_COCOTB_COVERAGE:
            self.log.error("cocotb-coverage not installed!")
            return
        
        self.cover_points = {}
        self._init_cover_points()
    
    def _init_cover_points(self) -> None:
        """初始化覆盖点"""
        if not HAS_COCOTB_COVERAGE:
            return
        
        # 地址覆盖点
        self.cover_points['addr'] = CoverPoint(
            f"{self.name}.addr",
            fv=lambda trans: trans.addr,
            bins=[
                (0, 0x3F),
                (0x40, 0x7F),
                (0x80, 0xBF),
                (0xC0, 0xFF)
            ]
        )
        
        # 读写覆盖点
        self.cover_points['write'] = CoverPoint(
            f"{self.name}.write",
            fv=lambda trans: trans.write,
            bins=[True, False]
        )
        
        # 交叉覆盖
        self.cover_points['cross'] = CoverCross(
            f"{self.name}.cross",
            items=[self.cover_points['addr'], self.cover_points['write']]
        )
    
    def sample(self, transaction) -> None:
        """采样事务"""
        if not HAS_COCOTB_COVERAGE:
            return
        
        for cp in self.cover_points.values():
            cp.sample(transaction)
    
    def report(self) -> None:
        """打印覆盖率报告"""
        if not HAS_COCOTB_COVERAGE:
            self.log.error("cocotb-coverage not installed!")
            return
        
        from cocotb_coverage.coverage import coverage_report
        coverage_report()