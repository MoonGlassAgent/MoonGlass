    def _sample_field(self, field_name: str, value: int) -> None:
        """采样单个字段"""
        if field_name not in self.bins:
            return
        
        for bin_obj in self.bins[field_name]:
            if bin_obj.min_val <= value <= bin_obj.max_val:
                if bin_obj.count == 0:
                    # 首次命中，更新覆盖率
                    self.coverage_data[field_name]['hit_bins'] += 1
                    self._update_coverage(field_name)
                bin_obj.count += 1
                break
    
    def _update_coverage(self, field_name: str) -> None:
        """更新覆盖率计算"""
        data = self.coverage_data[field_name]
        data['coverage'] = data['hit_bins'] / data['total_bins'] * 100
    
