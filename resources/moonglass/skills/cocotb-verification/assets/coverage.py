    def _add_cover_point(self, name: str, description: str, bins: List[CoverageBin]) -> None:
        """添加覆盖点"""
        self.bins[name] = bins
        self.coverage_data[name] = {
            'description': description,
            'total_bins': len(bins),
            'hit_bins': 0,
            'coverage': 0.0
        }
    
    def _create_range_bins(self, name: str, ranges: List[tuple], labels: List[str] = None) -> List[CoverageBin]:
        """创建范围仓"""
        bins = []
        for i, (min_val, max_val) in enumerate(ranges):
            label = labels[i] if labels else f"bin_{i}"
            bins.append(CoverageBin(f"{name}_{label}", min_val, max_val))
        return bins
    
    def _create_power_of_2_bins(self, name: str, max_val: int) -> List[CoverageBin]:
        """创建2的幂次仓"""
        bins = []
        power = 0
        while (1 << power) <= max_val:
            min_val = 1 << power
            max_bin = (1 << (power + 1)) - 1
            bins.append(CoverageBin(f"{name}_2pow{power}", min_val, max_bin))
            power += 1
            if power > 32:  # 防止无限循环
                break
        return bins
    
